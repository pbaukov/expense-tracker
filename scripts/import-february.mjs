// --- Build expense rows ---
const expenses = RAW.map(([date, rawCat, amount, description]) => {
  const mapped = CATEGORY_MAP[rawCat] ?? { category: rawCat, subcategory: '' };
  return {
    id: randomUUID(),
    date,
    amount,
    category: mapped.category,
    subcategory: mapped.subcategory,
    description: description || '',
  };
});

// --- Generate CSV ---
function csvEscape(val) {
  const str = String(val ?? '');
  return str.includes(',') || str.includes('"') || str.includes('\n')
    ? `"${str.replace(/"/g, '""')}"` : str;
}

const header = 'id,date,amount,category,subcategory,description';
const rows = expenses.map(e =>
  [e.id, e.date, e.amount, e.category, e.subcategory, e.description].map(csvEscape).join(',')
);
const csv = [header, ...rows].join('\n');

// --- Upload to Dropbox ---
console.log(`Uploading ${expenses.length} entries to Dropbox...`);

const body = Buffer.from(csv, 'utf8');

await new Promise((resolve, reject) => {
  const req = request({
    hostname: 'content.dropboxapi.com',
    path: '/2/files/upload',
    method: 'POST',
    headers: {
      'Authorization': `Bearer ${TOKEN}`,
      'Content-Type': 'application/octet-stream',
      'Content-Length': body.length,
      'Dropbox-API-Arg': JSON.stringify({ path: DROPBOX_PATH, mode: 'overwrite' }),
    },
  }, (res) => {
    let data = '';
    res.on('data', chunk => data += chunk);
    res.on('end', () => {
      if (res.statusCode === 200) {
        const total = expenses.reduce((s, e) => s + e.amount, 0);
        console.log(`Done! ${expenses.length} записів, загальна сума: ${total.toLocaleString()} грн.`);
        resolve();
      } else {
        console.error(`Upload failed (${res.statusCode}):`, data);
        reject(new Error(data));
      }
    });
  });
  req.on('error', reject);
  req.write(body);
  req.end();
});
